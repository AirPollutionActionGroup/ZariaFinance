-- V143: Change log for funding records (fund profile + its grant agreement).
--       Insert-only: one row per changed field, grouped by change_group (one
--       save or one status action). Values are stored as readable text, so the
--       log still reads correctly if a programme or master value is renamed.

CREATE TABLE funding_change_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_profile_id BIGINT       NOT NULL REFERENCES donor_fund_profile(id) ON DELETE CASCADE,
    grant_id        BIGINT,
    change_group    VARCHAR(40)  NOT NULL,
    action          VARCHAR(30)  NOT NULL,
    section         VARCHAR(60),
    field_label     VARCHAR(160),
    old_value       TEXT,
    new_value       TEXT,
    note            VARCHAR(1000),
    changed_by      VARCHAR(255),
    changed_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_funding_change_log_action CHECK (action IN (
        'CREATED', 'UPDATED', 'AGREEMENT_ADDED', 'APPROVED', 'ACTIVATED',
        'ON_HOLD', 'RESUMED', 'COMPLETED', 'CLOSED'))
);

CREATE INDEX idx_funding_change_log_profile ON funding_change_log (fund_profile_id, changed_at DESC, id DESC);

-- Starting point for records that existed before the log: when they were created,
-- when their agreement was recorded, and when it was approved. No field history
-- exists from before this migration.
INSERT INTO funding_change_log (fund_profile_id, change_group, action, section, field_label, new_value, note, changed_by, changed_at)
SELECT fp.id, 'start-' || fp.id, 'CREATED', 'Funding', 'Funding record', fp.profile_code,
       'Recorded before the change log started', fp.created_by, fp.created_at
FROM donor_fund_profile fp;

INSERT INTO funding_change_log (fund_profile_id, grant_id, change_group, action, section, field_label, new_value, changed_by, changed_at)
SELECT g.fund_profile_id, g.id, 'start-ga-' || g.id, 'AGREEMENT_ADDED', 'Agreement', 'Agreement',
       g.grant_code || ' · signed ' || to_char(g.agreement_date, 'DD Mon YYYY'), g.created_by, g.created_at
FROM grant_agreement g
WHERE g.fund_profile_id IS NOT NULL;

INSERT INTO funding_change_log (fund_profile_id, grant_id, change_group, action, section, field_label, new_value, note, changed_at)
SELECT g.fund_profile_id, g.id, 'start-ap-' || g.id, 'APPROVED', 'Status', 'Stage', 'Approved', g.approval_remarks,
       COALESCE(g.approval_date, g.updated_at)
FROM grant_agreement g
WHERE g.fund_profile_id IS NOT NULL AND g.is_approved = 1;
