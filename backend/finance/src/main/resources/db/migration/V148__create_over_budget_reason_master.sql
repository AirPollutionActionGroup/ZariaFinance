-- Over-budget reasons become a master (Masters → Over-budget reasons) instead of
-- a fixed list in the code. A debit note that takes its budget line over budget
-- points at one by id.
CREATE TABLE over_budget_reason_master (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(500),
    status      BOOLEAN NOT NULL DEFAULT true,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by  VARCHAR(255),
    updated_by  VARCHAR(255)
);

CREATE INDEX idx_over_budget_reason_status ON over_budget_reason_master(status);

-- The five reasons the form offered until now.
INSERT INTO over_budget_reason_master (name, description) VALUES
    ('Additional charge',    'An extra cost not in the budget'),
    ('FX difference',        'The exchange rate moved after the budget was set'),
    ('Price revision',       'The supplier raised the price'),
    ('Tax / GST adjustment', 'Tax or GST came out higher than budgeted'),
    ('Other',                'Anything else — explain it in the remarks');

ALTER TABLE debit_note ADD COLUMN over_budget_reason_id BIGINT REFERENCES over_budget_reason_master(id);

-- Carry over any reason already saved as one of the old codes.
UPDATE debit_note d
SET over_budget_reason_id = r.id
FROM over_budget_reason_master r
WHERE r.name = CASE d.reason
    WHEN 'ADDITIONAL_CHARGE' THEN 'Additional charge'
    WHEN 'FX_DIFFERENCE'     THEN 'FX difference'
    WHEN 'PRICE_REVISION'    THEN 'Price revision'
    WHEN 'TAX_ADJUSTMENT'    THEN 'Tax / GST adjustment'
    WHEN 'OTHER'             THEN 'Other'
END;

CREATE INDEX idx_debit_note_over_budget_reason ON debit_note(over_budget_reason_id);

ALTER TABLE debit_note DROP COLUMN reason;
